-- Student-facing RPCs verify both room code and roster membership.
create or replace function public.student_list_farsiyar_videos(p_room_code text, p_student_name text)
returns table(id bigint, title text, description text, storage_path text, created_at timestamptz)
language sql security definer set search_path = public as $$
  select v.id, v.title, v.description, v.storage_path, v.created_at
  from public.farsiyar_videos v
  where v.room_code = upper(trim(p_room_code))
    and exists (select 1 from public.farsiyar_classes c
      where c.room_code = v.room_code and c.roster @> jsonb_build_array(trim(p_student_name)))
  order by v.created_at desc;
$$;
revoke all on function public.student_list_farsiyar_videos(text,text) from public;
grant execute on function public.student_list_farsiyar_videos(text,text) to anon, authenticated;

create or replace function public.student_get_farsiyar_chat(p_room_code text, p_student_name text)
returns table(id bigint, sender_role text, sender_name text, body text, created_at timestamptz)
language sql security definer set search_path = public as $$
  select m.id, m.sender_role, m.sender_name, m.body, m.created_at
  from public.farsiyar_chat_messages m
  where m.room_code = upper(trim(p_room_code))
    and exists (select 1 from public.farsiyar_classes c
      where c.room_code = m.room_code and c.roster @> jsonb_build_array(trim(p_student_name)))
  order by m.created_at desc limit 100;
$$;
revoke all on function public.student_get_farsiyar_chat(text,text) from public;
grant execute on function public.student_get_farsiyar_chat(text,text) to anon, authenticated;

create or replace function public.student_send_farsiyar_chat(p_room_code text, p_student_name text, p_body text)
returns bigint language plpgsql security definer set search_path = public as $$
declare v_id bigint; v_code text := upper(trim(p_room_code)); v_name text := trim(p_student_name); v_body text := trim(p_body);
begin
  if length(v_body) < 1 or length(v_body) > 500 then raise exception 'INVALID_MESSAGE'; end if;
  if not exists (select 1 from public.farsiyar_classes c
    where c.room_code = v_code and c.roster @> jsonb_build_array(v_name)) then
    raise exception 'STUDENT_NOT_IN_ROSTER' using errcode = '42501';
  end if;
  insert into public.farsiyar_chat_messages(room_code,sender_role,sender_name,body)
    values(v_code,'student',v_name,v_body) returning id into v_id;
  return v_id;
end; $$;
revoke all on function public.student_send_farsiyar_chat(text,text,text) from public;
grant execute on function public.student_send_farsiyar_chat(text,text,text) to anon, authenticated;

create or replace function public.student_get_farsiyar_live_status(p_room_code text, p_student_name text)
returns table(is_live boolean, updated_at timestamptz)
language sql security definer set search_path = public as $$
  select coalesce(s.is_live,false), s.updated_at
  from public.farsiyar_classes c
  left join public.farsiyar_live_sessions s on s.room_code = c.room_code
  where c.room_code = upper(trim(p_room_code))
    and c.roster @> jsonb_build_array(trim(p_student_name));
$$;
revoke all on function public.student_get_farsiyar_live_status(text,text) from public;
grant execute on function public.student_get_farsiyar_live_status(text,text) to anon, authenticated;

-- Public bucket: uploaded videos can be watched by anyone who has their URL.
-- Upload/delete is restricted to an authenticated owner of the matching class.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('farsiyar-videos', 'farsiyar-videos', true, 104857600,
  array['video/mp4','video/webm','video/ogg','video/quicktime','video/x-matroska'])
on conflict (id) do nothing;

drop policy if exists farsiyar_video_upload_owner on storage.objects;
create policy farsiyar_video_upload_owner on storage.objects
  for insert to authenticated with check (
    bucket_id = 'farsiyar-videos'
    and exists (
      select 1 from public.farsiyar_classes c
      where c.room_code = split_part(name, '/', 1) and c.owner_id = auth.uid()
    )
  );
drop policy if exists farsiyar_video_delete_owner on storage.objects;
create policy farsiyar_video_delete_owner on storage.objects
  for delete to authenticated using (
    bucket_id = 'farsiyar-videos'
    and exists (
      select 1 from public.farsiyar_classes c
      where c.room_code = split_part(name, '/', 1) and c.owner_id = auth.uid()
    )
  );

