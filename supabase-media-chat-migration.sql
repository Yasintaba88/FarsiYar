-- FarsiYar media + chat + live status migration
-- Safe additive migration: does not drop or rewrite existing class/response/score data.
-- Run once in Supabase SQL Editor after reviewing the public-video note in README.

create table if not exists public.farsiyar_videos (
  id bigint generated by default as identity primary key,
  room_code text not null references public.farsiyar_classes(room_code) on delete cascade,
  owner_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (length(trim(title)) between 1 and 120),
  description text not null default '' check (length(description) <= 500),
  storage_path text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.farsiyar_chat_messages (
  id bigint generated by default as identity primary key,
  room_code text not null references public.farsiyar_classes(room_code) on delete cascade,
  sender_role text not null check (sender_role in ('teacher','student')),
  sender_name text not null check (length(trim(sender_name)) between 1 and 80),
  body text not null check (length(trim(body)) between 1 and 500),
  created_at timestamptz not null default now()
);

create index if not exists farsiyar_videos_room_created_idx
  on public.farsiyar_videos(room_code, created_at desc);
create index if not exists farsiyar_chat_room_created_idx
  on public.farsiyar_chat_messages(room_code, created_at desc);

create table if not exists public.farsiyar_live_sessions (
  room_code text primary key references public.farsiyar_classes(room_code) on delete cascade,
  is_live boolean not null default false,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

alter table public.farsiyar_videos enable row level security;
alter table public.farsiyar_chat_messages enable row level security;
alter table public.farsiyar_live_sessions enable row level security;

drop policy if exists farsiyar_videos_owner_select on public.farsiyar_videos;
